/*
 * libsweet-glapp.dylib (0191): OpenGL ES for apps, the half that has to be linked against iOS's OpenGLES only.
 *
 * An app calls the gl* functions OpenGLES.framework exports. Those find their context in OpenGLES's own state, which
 * our EAGLContexts (userland/gpu/eagl.c, libsweet-gl.dylib, on Mesa) never fill in: every call went nowhere. This
 * library interposes (dyld's __DATA,__interpose) each of those exports with one that calls the table of the context
 * that +[EAGLContext setCurrentContext:] made the thread's (sweet_gl_current_table(), libsweet-gl.dylib). It cannot be
 * part of libsweet-gl itself: there the gl* names bind to Mesa's functions, and the interposing would aim at those.
 *
 * The interposers are generated by gpu/mkeagl.py (section EAGL_GEN_INTERPOSE of out/eagl_gen.h) for every name of
 * every entry the table has a function for. A name OpenGLES does not export is weak (its interposer is never used).
 * Make an app load it with tools/insert-dylib.py APP_BINARY /usr/lib/libsweet-glapp.dylib (it loads libsweet-gl).
 * MIT, as userland/.
 */
#include <stdint.h>
#include <stddef.h>

/* OpenGL ES's types by their ABI (no OpenGLES header: its declarations of the same functions would clash) */
typedef uint32_t GLbitfield;
typedef uint8_t GLboolean;
typedef char GLchar;
typedef int32_t GLclampx;
typedef uint32_t GLenum;
typedef int32_t GLfixed;
typedef float GLfloat;
typedef float GLclampf;
typedef int32_t GLint;
typedef int64_t GLint64;
typedef long GLintptr;
typedef int32_t GLsizei;
typedef long GLsizeiptr;
typedef struct __GLsync *GLsync;
typedef uint8_t GLubyte;
typedef uint32_t GLuint;
typedef uint64_t GLuint64;
typedef int8_t GLbyte;
typedef int16_t GLshort;
typedef uint16_t GLushort;
typedef void GLvoid;
typedef uint16_t GLhalf;

extern void **sweet_gl_current_table(void);     /* libsweet-gl.dylib */

#define GLAPP_INTERPOSE(replacement, replacee)                                                          \
	__attribute__((used)) static const struct {                                                     \
		const void *replacement_;                                                               \
		const void *replacee_;                                                                  \
	} glapp_interpose_##replacee __attribute__((section("__DATA,__interpose"))) = {               \
		(const void *)(uintptr_t)&replacement, (const void *)(uintptr_t)&replacee               \
	};

#define EAGL_GEN_INTERPOSE
#include "eagl_gen.h"
